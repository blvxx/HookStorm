"""Export HookStorm scenarios as reusable pytest integration tests."""

from __future__ import annotations

from pathlib import Path
from pprint import pformat
from typing import Any


def render_pytest(scenario: dict[str, Any]) -> str:
    """Render a pytest module embedding a normalized scenario without secrets or targets."""
    scenario_literal = pformat(scenario, width=88, sort_dicts=False)
    return f'''"""Generated by HookStorm. See https://github.com/blvxx/HookStorm."""

from __future__ import annotations

import asyncio
import os

import pytest

from hookstorm.report import render_json
from hookstorm.runner import run_scenario

SCENARIO = {scenario_literal}


@pytest.mark.integration
def test_hookstorm_scenario() -> None:
    """Run the embedded scenario against HOOKSTORM_TARGET."""
    target = os.getenv("HOOKSTORM_TARGET")
    if not target:
        pytest.skip("Set HOOKSTORM_TARGET to run this webhook integration test")

    result = asyncio.run(
        run_scenario(
            SCENARIO,
            target,
            allow_remote=os.getenv("HOOKSTORM_ALLOW_REMOTE") == "1",
            secret=os.getenv("HOOKSTORM_SECRET"),
        )
    )
    assert result["summary"]["success"], render_json(result)
'''


def write_pytest(scenario: dict[str, Any], path: str | Path) -> Path:
    """Write a generated pytest module and return its path."""
    output = Path(path)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(render_pytest(scenario), encoding="utf-8")
    return output
